const assert=require('node:assert/strict'),path=require('path');
require('./test-support/build.cjs')();
const T=p=>require(path.resolve('.test-build/tree/'+p));
const {resolveAlignment,alignmentIntersections}=T('core/common/resolved-alignment.cjs');
const pts=[{x:0,y:0},{x:100,y:0,radius:40},{x:100,y:100}];
const a=resolveAlignment(pts),near=(x,y,e=1e-7)=>assert.ok(Math.abs(x-y)<e,`${x} ≠ ${y}`);
near(a.length,120+20*Math.PI);
near(a.pointAt(60+10*Math.PI).x,60+40/Math.sqrt(2));
near(a.project(a.pointAt(90)).station,90);
assert.equal(alignmentIntersections(a,resolveAlignment([{x:95,y:-100},{x:95,y:5}])).length,0);
const hit=alignmentIntersections(a,resolveAlignment([{x:80,y:2},{x:80,y:100}]))[0];
near(hit.point.x,80);near(hit.point.y,40-Math.sqrt(1200));
const reverse=resolveAlignment([...pts].reverse());
near(reverse.project(a.pointAt(90)).station,a.length-90);
const t=a.tangentAt(90),u=reverse.tangentAt(a.length-90);near(t.x,-u.x);near(t.y,-u.y);
near(a.mapChordStation(200),a.length);near(a.mapChordStation(100),60+10*Math.PI);
const large=resolveAlignment([{x:0,y:0},{x:1000,y:0,radius:300},{x:1000,y:1000}]);
assert.ok(large.pieces.some(p=>p.kind==='arc'&&p.radius===300));
console.log('PASS canonical alignment: exact length/projection, real/phantom crossings, reversal, station map, radius > 200');
