// PR D: semantic override contract and command regression. No manual pavement rendering is inferred.
const assert=require('node:assert/strict'),path=require('node:path');
require('./test-support/build.cjs')();
const T=p=>require(path.resolve('.test-build/tree/'+p));
const model=T('core/junction/model.cjs'),automatic=T('core/junction/automatic-lane-mapping.cjs');
const ov=T('core/road-first/lane-connector-overrides.cjs');
const reviewGeometry=T('core/road-first/connector-review-geometry.cjs');
const commands=T('core/road-first/commands.cjs'),project=T('core/road-first/project.cjs');
const treatments=T('core/road-first/leg-treatments.cjs');
const geo=T('core/junction/geometry.cjs');
const d=model.initial(),before=structuredClone(d),pavement=geo.edges(d);
const bindings=[0,1,2,3].map(i=>({armId:i,leg:'R'+i+':ahead'}));
const auto=automatic.automaticLaneMapping(d);
assert(auto.connections.length>0,'auto mapping exists');
const source=(c)=>({leg:bindings[c.from.armId].leg,role:c.from.role,laneIndex:c.from.laneIndex});
const target=(arm,role,index)=>({leg:bindings[arm].leg,role,laneIndex:index});
const through=auto.connections.find(c=>c.from.armId===0&&c.movement==='through');
assert(through,'through connection present');
const suppress={from:source(through),movement:'through',mode:'suppress'};
const suppressed=ov.resolveConnectorOverrides(d,bindings,[suppress]);
assert(!suppressed.connections.some(c=>c.from.armId===through.from.armId&&c.from.laneIndex===through.from.laneIndex&&c.movement==='through'),'suppression removes only selected generated movement');
assert(suppressed.connections.some(c=>c.from.armId!==through.from.armId),'other movements unaffected');
assert.deepEqual(ov.resolveConnectorOverrides(d,bindings,[]).connections.map(x=>({...x,origin:undefined})),auto.connections.map(x=>({...x,origin:undefined})),'empty override keeps generated mapping');
const right=auto.connections.find(c=>c.from.armId===0&&c.movement==='right');
assert(right,'right-turn connection present');
assert(automatic.eligibleTurnTargets(d,0,'right').includes(right.to.armId));
const replace={from:source(right),movement:'right',mode:'replace',to:target(right.to.armId,'main',1)};
assert.equal(ov.connectorOverrideError([replace]),null);
const changed=ov.resolveConnectorOverrides(d,bindings,[replace]);
assert(!changed.issues.some(i=>i.kind==='manual-review'),'valid manual override');
const manual=changed.connections.find(c=>c.origin==='manual');
assert(manual&&manual.to.laneIndex===1,'manual chooses specified receiver');
assert.equal(changed.connections.filter(c=>c.from.armId===right.from.armId&&c.from.laneIndex===right.from.laneIndex&&c.movement==='right').length,1);
assert.deepEqual(d,before,'resolver does not mutate authored junction');
assert.deepEqual(geo.edges(d),pavement,'base pavement stays unchanged');
const positioned={id:'J-1',name:'test',x:123,y:-47,z:6,rotation:35,design:d};
const visual=reviewGeometry.connectorReviewGeometry(positioned,bindings,[replace]);
assert.equal(visual.elevation,6,'3D and 2D review use the actual junction elevation');
const shown=visual.lines.find(c=>c.origin==='manual');
assert(shown,'same manually authored lane exists in the visual review');
const manualStart=changed.connections.find(c=>c.origin==='manual').fromPoint;
const radians=35*Math.PI/180;
const expectedWorld={x:123+manualStart.x*Math.cos(radians)-manualStart.y*Math.sin(radians),
  y:-47+manualStart.x*Math.sin(radians)+manualStart.y*Math.cos(radians)};
assert(Math.hypot(shown.start.x-expectedWorld.x,shown.start.y-expectedWorld.y)<1e-5,'review lane anchors transform local geometry consistently to world');
const pickTargets=reviewGeometry.connectorReviewTargets(positioned,bindings,replace.from,replace.movement);
assert(pickTargets.some(t=>t.ref.leg===replace.to.leg&&t.ref.laneIndex===replace.to.laneIndex),'plan can pick existing canonical receiving lane');
assert.deepEqual(d,before,'review geometry does not change junction design');
assert.deepEqual(ov.resolveConnectorOverrides(JSON.parse(JSON.stringify(d)),bindings,JSON.parse(JSON.stringify([replace]))),changed,'stable JSON reopen');
assert(ov.connectorOverrideError([replace,replace]),'duplicate from+movement rejected');
assert(ov.connectorOverrideError([{...replace,to:{...replace.to,laneIndex:99}}]),'out-of-bounds lane index rejected');

const missing=structuredClone(d);missing.arms[right.to.armId].outgoing=1;
assert(ov.resolveConnectorOverrides(missing,bindings,[replace]).issues.some(i=>i.kind==='manual-review'),'missing target remains authored but reviewed');
assert.equal(replace.to.laneIndex,1,'stale review does not rewrite authored override');
const arrows=structuredClone(d);
arrows.arms[right.from.armId].laneMarkings=model.withLaneArrow(arrows.arms[right.from.armId],'incoming',right.from.role,right.from.laneIndex,'straight');
assert(ov.resolveConnectorOverrides(arrows,bindings,[replace]).issues.some(i=>i.kind==='manual-review'),'incompatible turn arrow is reviewed');
const slip=T('core/junction/slip-model.cjs').addSlip(d,0);
const slipBindings=bindings;
const left=auto.connections.find(c=>c.from.armId===0&&c.movement==='left');
assert(left);
const slipAttempt={from:source(left),movement:'left',mode:'suppress'};
assert(ov.resolveConnectorOverrides(slip,slipBindings,[slipAttempt]).issues.some(i=>i.kind==='manual-review'),'Slip-owned turn cannot be overridden');
const stale={...replace,from:{...replace.from,leg:'missing:ahead'}};
assert(ov.resolveConnectorOverrides(d,bindings,[stale]).issues.some(i=>i.kind==='manual-review'),'stale road-leg identifier is review, not auto retarget');
const flipped=ov.remapConnectorOverrides([replace],leg=>leg.endsWith(':ahead')?leg.replace(':ahead',':behind'):leg);
assert.equal(flipped[0].from.leg,'R0:behind');
assert(flipped[0].to.leg.endsWith(':behind'),'source and receiving references remap together');

// Work through the actual road-first command layer / persisted Decision.
const sec={forwardLanes:2,backwardLanes:2,laneWidth:3.25,median:2,walk:2};
const a={id:'A',name:'ถนนหลัก',points:[{x:-300,y:0},{x:300,y:0}],section:sec};
const b={id:'B',name:'ถนนรอง',points:[{x:0,y:-250},{x:0,y:250}],section:sec};
let ed=commands.createEditor({kind:'road-first',schemaVersion:3,title:'test',roads:[],decisions:[],options:{}});
ed=commands.runCommand(ed,{type:'road.add',road:a}).editor;
ed=commands.runCommand(ed,{type:'road.add',road:b}).editor;
const confirmed=ed.project.decisions.find(d=>d.decision==='junction');
assert(confirmed,'auto junction created');
const compiled=project.compileRoadFirstProject(ed.project);
const jid=Object.keys(compiled.sources.junctions).find(id=>compiled.sources.junctions[id]===confirmed.candidateId);
const j=compiled.project.junctions.find(x=>x.id===jid);
const legs=compiled.legs.filter(x=>x.junctionId===jid);
const bs=legs.map(l=>({armId:l.armId,leg:l.roadId+':'+l.side}));
const present=automatic.automaticLaneMapping(j.design).connections.find(c=>c.movement==='through');
assert(present);
const authored={from:{leg:bs.find(x=>x.armId===present.from.armId).leg,role:present.from.role,laneIndex:present.from.laneIndex},movement:'through',mode:'suppress'};
const prior=structuredClone(ed.project);
let out=commands.runCommand(ed,{type:'junction.setConnector',candidateId:confirmed.candidateId,override:authored});
assert.equal(out.result.error,null,out.result.error);
ed=commands.endGesture(out.editor);
const current=ed.project.decisions.find(x=>x.candidateId===confirmed.candidateId);
assert.deepEqual(current.treatments.connectors,[authored],'the authored only delta is persisted');
assert.equal(project.validateRoadFirstProject(ed.project),null,'optional field accepted without schema bump');
const reloaded=project.normalizeRoadFirstProject(JSON.parse(JSON.stringify(ed.project)));
assert.deepEqual(reloaded.decisions.find(x=>x.candidateId===confirmed.candidateId).treatments.connectors,[authored]);
const captured=treatments.captureTreatments(ed.project.roads,ed.project.decisions,project.compileRoadFirstProject(ed.project).project,ed.project.options);
assert.deepEqual(captured.decisions.find(x=>x.candidateId===confirmed.candidateId).treatments.connectors,[authored],'advanced editor capture preserves manual overrides');
assert.deepEqual(commands.undo(ed).editor.project,prior,'one undo removes authored change');
const restored=commands.redo(commands.undo(ed).editor).editor;
assert.deepEqual(restored.project,ed.project,'redo restores authored override');
const reset=commands.executeCommand(ed.project,{type:'junction.resetConnector',candidateId:confirmed.candidateId,from:authored.from,movement:'through'});
assert.equal(reset.error,null);
assert.equal(reset.project.decisions.find(x=>x.candidateId===confirmed.candidateId).treatments.connectors,undefined);
const wrong=commands.executeCommand(ed.project,{type:'junction.setConnector',candidateId:confirmed.candidateId,override:{...authored,from:{...authored.from,laneIndex:7}}});
assert(wrong.error,'new impossible override rejected');assert.deepEqual(wrong.project,ed.project,'invalid command atomic');
assert.equal(project.validateRoadFirstProject(prior),null,'legacy optional-absent project remains valid');

console.log('PASS PR D contract: generated/manual/suppressed, LHT arrows, Slip, stale review, JSON, capture, atomic command, undo/redo, reset and old files');
